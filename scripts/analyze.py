"""Load the fitted model and write every table, chart and number in reports/.

    python scripts/analyze.py                       # uses artifacts/model.binpb, writes reports/
    python scripts/analyze.py --model X --out-dir Y # e.g. a quick smoke-test model
"""

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

import pandas as pd  # noqa: E402

from mmm_case import analysis, charts, config, paths  # noqa: E402


def money(x: float) -> str:
    return f"${x / 1e6:,.1f}M"


def ci(row, var, fmt="{:.2f}") -> str:
    return f"{fmt.format(row[f'{var}_mean'])} [{fmt.format(row[f'{var}_ci_low'])}, {fmt.format(row[f'{var}_ci_high'])}]"


def metrics_table(m: pd.DataFrame, half_life: pd.DataFrame) -> str:
    hl = half_life.set_index("channel")["half_life_weeks"].to_dict()
    max_lag = int(half_life["max_lag_weeks"].iloc[0])
    lines = [
        "| Channel | Spend | Share of spend | Incremental revenue | ROI | mROI | mROI / ROI | Adstock half-life |",
        "|---|---:|---:|---:|---|---|---:|---:|",
    ]
    for _, r in m.iterrows():
        total = r["channel"].startswith("All")
        half = hl.get(r["channel"])
        if total:
            half_s = ""
        elif half is None or pd.isna(half):
            half_s = f"> {max_lag} wk"
        else:
            half_s = f"{half:.1f} wk"
        mroi_s = "" if total else ci(r, "mroi")
        ratio_s = "" if total else f"{r['mroi_mean'] / r['roi_mean']:.2f}"
        name = "**All paid channels**" if total else r["channel"]
        lines.append(
            f"| {name} | {money(r['spend'])} | {r['pct_of_spend']:.0f}% | "
            f"{money(r['incremental_outcome_mean'])} | {ci(r, 'roi')} | {mroi_s} | {ratio_s} | {half_s} |"
        )
    return "\n".join(lines)


def optimization_table(t: pd.DataFrame) -> str:
    lines = ["| Channel | Current spend | Optimized spend | Change | Incremental revenue: current | optimized |",
             "|---|---:|---:|---:|---:|---:|"]
    for _, r in t.iterrows():
        lines.append(f"| {r['channel']} | {money(r['current_spend'])} | {money(r['optimized_spend'])} | "
                     f"{r['spend_change_pct'] * 100:+.0f}% | {money(r['current_incremental_revenue'])} | "
                     f"{money(r['optimized_incremental_revenue'])} |")
    return "\n".join(lines)


def update_readme(md: list[str]) -> None:
    """Replace the generated block in README.md with the headline sections of results.md."""
    readme = ROOT / "README.md"
    if not readme.exists():
        return
    text = readme.read_text()
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    if start not in text or end not in text:
        return
    body = "\n".join(line.replace("## ", "### ", 1) if line.startswith("## ") else line
                     for line in md[2:])
    note = "<!-- generated by scripts/analyze.py from reports/results.json; do not edit by hand -->"
    new = text[: text.index(start)] + f"{start}\n{note}\n{body}\n{end}" + text[text.index(end) + len(end):]
    readme.write_text(new)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--model", default=str(paths.MODEL_FILE))
    p.add_argument("--out-dir", default=str(paths.REPORTS))
    p.add_argument("--skip-matrix", action="store_true", help="skip the 20-pair reallocation matrix")
    args = p.parse_args()
    out = Path(args.out_dir)
    (out / "figures").mkdir(parents=True, exist_ok=True)

    from meridian.schema.serde import meridian_serde

    t0 = time.time()
    mmm = meridian_serde.load_meridian(args.model)

    diag = analysis.diagnostics(mmm)
    rev = analysis.review(mmm)
    metrics = analysis.channel_metrics(mmm)
    half_life = analysis.adstock_half_life(mmm)
    curves = analysis.response_curves(mmm)
    realloc = analysis.reallocation(mmm, metrics)
    opt = analysis.optimize_budget(mmm)
    level = analysis.budget_level(mmm, 0.9)
    matrix = None if args.skip_matrix else analysis.reallocation_matrix(mmm)

    metrics.to_csv(out / "channel_metrics.csv", index=False)
    half_life.to_csv(out / "adstock_half_life.csv", index=False)
    curves.to_csv(out / "response_curves.csv", index=False)
    opt["table"].to_csv(out / "budget_optimization.csv", index=False)
    if matrix is not None:
        matrix.to_csv(out / "reallocation_matrix.csv", index=False)

    paid = metrics[~metrics["channel"].str.startswith("All")]
    charts.roi_mroi(paid, out / "figures" / "roi_mroi.png", config.CONFIDENCE_LEVEL)
    charts.response_curves(curves, out / "figures" / "response_curves.png")
    charts.budget_shift(opt["table"], out / "figures" / "budget_shift.png")

    results = {
        "diagnostics": diag,
        "model_review": rev,
        "reallocation": realloc,
        "optimization": {k: v for k, v in opt.items() if k != "table"},
        "budget_level": level,
        "total_paid": metrics[metrics["channel"].str.startswith("All")].to_dict("records"),
        "confidence_level": config.CONFIDENCE_LEVEL,
        "analysis_runtime_seconds": round(time.time() - t0, 1),
    }
    (out / "results.json").write_text(json.dumps(results, indent=2, default=str) + "\n")

    r = realloc
    d = r["change_in_incremental_revenue"]
    o = opt["lift_draws"]
    md = [
        "# Results (generated by scripts/analyze.py; do not edit by hand)",
        "",
        f"Credible intervals are {int(config.CONFIDENCE_LEVEL * 100)}% posterior intervals.",
        "",
        "## Channel ROI and mROI",
        "",
        metrics_table(metrics, half_life),
        "",
        "## Reallocation scenario",
        "",
        f"Move {r['share']:.0%} of **{r['source']}**'s budget (lowest mROI, {r['source_mroi']:.2f}) "
        f"to **{r['target']}** (highest mROI, {r['target_mroi']:.2f}): {money(r['spend_moved'])} "
        f"of {money(r['total_spend'])} total spend, total unchanged.",
        "",
        f"- Change in incremental revenue: **{money(d['mean'])}** "
        f"[{money(d['ci_low'])}, {money(d['ci_high'])}]; probability it is positive: {d['prob_positive']:.1%}.",
        f"- That is {r['change_per_dollar_moved']:.2f} of extra revenue per dollar moved, and "
        f"{d['mean'] / r['base_incremental_revenue']['mean']:+.1%} on total paid-media incremental revenue "
        f"({money(r['base_incremental_revenue']['mean'])}).",
        "",
        "## Budget optimization (fixed budget)",
        "",
        f"Bounds: {opt['spend_bounds']}. Total budget {money(opt['total_budget'])}.",
        "",
        optimization_table(opt["table"]),
        "",
        f"- Lift in incremental revenue, recomputed draw by draw: **{money(o['mean'])}** "
        f"[{money(o['ci_low'])}, {money(o['ci_high'])}]; optimizer's own point estimate: "
        f"{money(opt['optimizer_reported_lift'])}.",
        "",
        "## Budget level: cut every channel by 10%",
        "",
        f"- Spend falls by {money(-level['spend_change'])}; incremental revenue falls by "
        f"**{money(-level['change_in_incremental_revenue']['mean'])}** "
        f"[{money(-level['change_in_incremental_revenue']['ci_high'])}, "
        f"{money(-level['change_in_incremental_revenue']['ci_low'])}].",
        f"- So the last 10% of the budget returns {level['revenue_per_dollar_of_spend_change']:.2f} of revenue per "
        f"dollar. Probability that the cut loses less revenue than it saves in spend: "
        f"{level['prob_revenue_change_smaller_than_spend_change']:.1%}.",
        "",
        "## Diagnostics",
        "",
        f"- Max R-hat: {diag['max_rhat']:.3f} (`{diag['max_rhat_parameter']}`); parameters above "
        f"{diag['rhat_threshold']}: {diag['n_parameters_rhat_over_threshold']}.",
        "- In-sample national fit: " + ", ".join(f"{k} {v:.3f}" for k, v in diag["national_fit"].items()) + ".",
        f"- Meridian ModelReviewer: {rev['overall_status']}, health score {rev['health_score']:.2f}. "
        f"{rev['summary_message']}",
        "",
        "| Review check | Result |",
        "|---|---|",
        *[f"| {c['check']} | {c['case']} |" for c in rev["checks"]],
    ]
    if matrix is not None:
        best = matrix.sort_values("mean", ascending=False).iloc[0]
        worst = matrix.sort_values("mean").iloc[0]
        md += [
            "",
            "## All 20 one-way reallocations of 10%",
            "",
            f"- Best: {best['source']} -> {best['target']}, {money(best['mean'])} "
            f"[{money(best['ci_low'])}, {money(best['ci_high'])}].",
            f"- Worst: {worst['source']} -> {worst['target']}, {money(worst['mean'])} "
            f"[{money(worst['ci_low'])}, {money(worst['ci_high'])}].",
            "- Full table: `reports/reallocation_matrix.csv`.",
        ]
    (out / "results.md").write_text("\n".join(md) + "\n")
    if out.resolve() == paths.REPORTS.resolve():
        update_readme(md)
    print("\n".join(md))
    print(f"\nanalysis runtime {results['analysis_runtime_seconds']}s")


if __name__ == "__main__":
    main()
